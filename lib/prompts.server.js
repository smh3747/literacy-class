function buildRubricText(rubrics) {
  return rubrics.map((r, i) =>
    `${i + 1}. ${r.name} (${r.score}점)${r.hint ? `\n   → 평가 포인트: ${r.hint}` : ''}`
  ).join('\n')
}

// 채점 시점의 오늘 날짜(KST) 안내 줄 — AI가 자기 현재를 과거(2024~25)로 착각해
// 학생이 인용한 최신 자료를 "미래 자료"로 오지적하는 문제 차단(실사례).
// 서버(Vercel)는 UTC라 new Date()를 그대로 포맷하면 자정 전후 하루 어긋남 → Asia/Seoul 고정.
function todayLineKST() {
  const d = new Intl.DateTimeFormat('ko-KR', { timeZone: 'Asia/Seoul', year: 'numeric', month: 'long', day: 'numeric' }).format(new Date())
  return `오늘은 ${d}입니다. 학생 글의 연도·날짜·자료 인용은 이 날짜를 기준으로 판단하고, 이 날짜보다 앞선 자료를 "미래의 일"이라고 잘못 지적하지 마세요.`
}

